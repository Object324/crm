    public function get_distance_query($r_latitude,$r_longitude,$r_page_query){
        $from_split = explode('FROM',$r_page_query);
        $where_split = explode('WHERE',$from_split[1]);
        $r = 6371.393;
        $cirWE = $r_longitude*pi()/180;
        $cirNS = $r_latitude*pi()/180;
        $store_query = "round($r*ACOS(COS($cirNS)*COS(ld_account.latitude*pi()/180)*COS($cirWE-ld_account.longtitude*pi()/180)+SIN($cirNS)*SIN(ld_account.latitude*pi()/180))*1000)";
        $list_query = "select ld_account.accountid,ifnull( $store_query,12756000) as distance from $where_split[0] where ".$where_split[1];

        //@edit:liushuai,2020-09-11,reason:【ID1001096】拜访签到选择客户单据列表界面功能优化
        global $adb;
        $date = date('Ymd');
        $file_path = globalStatic::$root_directory.'user_privileges/sigin_account_count.txt';
        if(file_exists($file_path)){
            $account_count_info = json_decode(file_get_contents($file_path));
            if (isset($account_count_info[$date])) {   //如果有今天的日期客户数，直接取，没有的话就更新进去
                $count = $account_count_info[$date];
            }else{
                $count_res= $adb->query('select count(accountid) as count from ld_account');
                $count = $adb->query_result($count_res,0,'count');
                file_put_contents($file_path, json_encode(array($date,$count)));
            }
        }else{
            //第一次创建,只执行一次
            $count_res= $adb->query('select count(accountid) as count from ld_account');
            $count = $adb->query_result($count_res,0,'count');
            file_put_contents($file_path, json_encode(array($date,$count)));
        }
        
        if($count > 100000){
            $orderby = ' ld_account.modifiedtime desc,ld_account.accountid desc';
        }else{
            $orderby = ' distance asc,ld_account.createdtime desc,ld_account.accountid desc';
        }
        return array('query'=>$list_query,'order'=>$orderby,'distancecolumnname'=>" ifnull( $store_query,12756000) as distance ");
    }
