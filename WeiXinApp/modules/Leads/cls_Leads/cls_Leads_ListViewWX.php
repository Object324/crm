    public  function setFilterRequest()
    {
        parent::setFilterRequest(); // TODO: Change the autogenerated stub
        if(!empty($_REQUEST['filter'])){
            $filter_arr = $_REQUEST['filter'];
            if(empty($filter_arr['accounttype'])){
                crm_load_class_file('cls_PublicLeads', 'modules/Leads');
                $cls_PublicLeads = new cls_PublicLeads('Leads');
                $public_account = $cls_PublicLeads->getPublicAccount();
                if($public_account['status'] == 'yes'){
                    if($public_account['show_publicaccount_tab'] == 'yes'){
                        $_REQUEST['pagepublicaccounttype'] = 'ALLACCOUNT';
                    }else{
                        $_REQUEST['pagepublicaccounttype'] = 'DEFAULTALLACCOUNT';
                    }
                }else{
                    $_REQUEST['pagepublicaccounttype'] = 'ALLACCOUNT';
                }
            }else{
                $_REQUEST['pagepublicaccounttype'] = $filter_arr['accounttype'];
            }
        }
    }

    public function setreturnJson_listContent()
    {
        global $current_user;
        parent::setreturnJson_listContent(); // TODO: Change the autogenerated stub
        if($_REQUEST['linkemodule_category'] =='yes') return false;
        $accounttype['fieldname'] = 'accounttype';
        $accounttype['fieldlabel'] = '是否公海';//gyqCN
        $accounttypeOp = [];
        //公海客户模块筛选条件中不显示公海条件
        if(empty($accounttypeOp)||$_REQUEST['publicaccounts']=='yes'){
            return false;
        }else{
            foreach($accounttypeOp as $key=>$val){
                $accounttypeOp[$key]['select'] = $key==0?'yes':'no';
            }
            $accounttype['option'] = $accounttypeOp;
            array_unshift($this->jsonArr['list'],$accounttype);
        }
    }

    public function init_custom_special(){
        global $viewid,$adb; //查询语句排序需要
        if (!empty($_REQUEST['pagepublicaccounttype'])) {
            $accounttype = $_REQUEST['pagepublicaccounttype'];
        } else {
            $accounttype = "ALLACCOUNT";
        }
        $_REQUEST['accounttype'] = $accounttype;
        if (isset($_REQUEST['viewid']) && $_REQUEST['viewid']) {
            $viewid = $_REQUEST['viewid'];
            $_REQUEST['viewname'] = $viewid;
        }else {
            //edit:can  20220808  54439：查询分类：每个用户登陆系统时显示自己设置“自定义显示默认分类”
             $sql='select ld_customview.setdefault,ld_user_module_preferences.default_cvid,ld_customview.cvid,ld_user_module_preferences.userid from  ld_customview
                 left join ld_user_module_preferences
                 on ld_customview.cvid=ld_user_module_preferences.default_cvid
                  where ld_customview.entitytype=? and (setdefault=1 or (ld_user_module_preferences.userid=?)) 
                  and (ld_customview.customcategory=?)
                  order by ld_user_module_preferences.default_cvid desc ';
              $result=$adb->pquery($sql,array($this->module,$current_user->id,$accounttype));
             $rows=$adb->num_rows($result);
            
             for($i=0;$i<$rows;$i++)
             {
                $default_cvid=$adb->query_result($result,$i,'default_cvid');
                  $userid=$adb->query_result($result,$i,'userid');
                
                if($default_cvid>0&&$userid==$current_user->id)
                {
                    $viewid=$default_cvid;
                    break;
                   
                }
             }
            if( empty($viewid))
                 $viewid = $this->customview->getViewIdByName('All',$this->module);
             $_REQUEST['viewid']=$viewid;
        }
        if ($viewid == 0 && is_numeric($_REQUEST['viewid'])) {
            ConvertTojsonString('-1', null, getFixedLabel('NOPERMITTEDEXECUTE'));
        }
        if (!isset($_REQUEST['viewid'])) {
            $_REQUEST['viewid'] = $this->customview->getViewIdByName('All',$this->module);
            $_REQUEST['viewname'] = 'SmOwner_Search_Me';
        }
        if ($_REQUEST['viewid'] == 'Leads_publicLeads') {
            $_REQUEST['viewid'] = 'SmOwner_Search_All';
            $_REQUEST['viewname'] = 'Leads_publicLeads';
        }

        $this->viewid = $viewid;
    }
