    public function ChinaMap(){
        $main_module_fields=$this->focus->fieldobj->getModuleFields();
        $arrfieldLabels=$this->focus->fieldobj->getFieldLables();
        $where_arr1  = array();
        $k = 0;
        if($_REQUEST['bill_state']=='上海'||$_REQUEST['bill_state']=='上海市')
        {
            $bill = array('bill_state','bill_area');
        }
        else
            $bill = array('bill_state','bill_city');
        foreach($main_module_fields as $fieldname=>$fieldinfo){
            if(in_array($fieldname,$bill)){
                $columncondition = '';
                $tablename=$fieldinfo->getTableName();
                $columnname=$fieldinfo->getColumnName();
                if(!empty($columnname)){
                    if($fieldname == 'bill_area')$fieldname = 'bill_city';
                    $where_arr1[] = '('.$tablename.'.'.$fieldname.' like \'%'.$_REQUEST[$fieldname].'%\')';
                }
                $k++;
            }
        }
        $groupcondition='';
        $where_arr2 = array();
        if(($_REQUEST['bill_state']=='上海')||($_REQUEST['bill_state']=='北京')
            ||($_REQUEST['bill_state']=='天津')||($_REQUEST['bill_state']=='重庆'))
        {
            $fieldinfo=$main_module_fields['bill_state'];
            if($fieldinfo&&$fieldinfo->getFieldName()!='')
            {
                $where_arr2[] = '(ld_account.bill_state like \'%'.$_REQUEST['bill_state'].'市%\')';
            }
            $fieldinfo=$main_module_fields['bill_area'];
            if($fieldinfo&&$fieldinfo->getFieldName()!='') {
                $where_arr2[]  = '(ld_account.bill_area like \'%'.$_REQUEST['bill_city'].'%\')';
            }
        }
        if(count($where_arr2) >0){
            $where  = ' and ('.implode(' and ',$where_arr1).' or '.implode(' and ',$where_arr2).')';
        }else{
            $where  = ' and '.implode(' and ',$where_arr1);
        }
        return $where;
    }
